import { formatSeconds } from "./format";
import { meetingVolumeControls } from "./meetingVolumeControls.mjs";

/** Map authoritative room playback and local controls to the Studio workspace. */
export default function buildWorkspaceProps({
  sensors,
  handleDragStart,
  handleDragOver,
  handleDragEnd,
  handleDragCancel,
  activeDrag,
  displayName,
  isAuthed,
  isAuthChecked,
  authBusy,
  loginName,
  setLoginName,
  password,
  setPassword,
  confirmPassword,
  setConfirmPassword,
  isRegisterMode,
  setIsRegisterMode,
  login,
  register,
  logout,
  userLogin,
  account,
  canManageAccount,
  showAdminBack,
  conference,
  roomSlug,
  roomSlugInput,
  roomListedInput,
  setRoomSlugInput,
  setRoomListedInput,
  slugBusy,
  audioRef,
  currentLabel,
  state,
  isSeekingRef,
  seekValue,
  setSeekValue,
  onSeek,
  localVolume,
  localMuted,
  outputForcedMuted,
  toggleLocalMute,
  onLocalVolumeChange,
  unlockAudio,
  queueEntries,
  renderQueueIds,
  sendAction,
  libraryState,
  libraryBusy,
  theme,
  setTheme,
  themeBusy,
  showHotkeys,
  setShowHotkeys,
  isHydrated,
  interactionToken,
  bumpInteraction,
  deleteTarget,
  clearDeleteTarget,
  confirmDelete,
  notice,
  showNotice,
}) {
  const liveDuration = Number(audioRef?.current?.duration);
  const resolvedDuration =
    Number.isFinite(liveDuration) && liveDuration > 0
      ? liveDuration
      : state?.current?.duration ?? state?.position ?? 0;

  const volumeControls = meetingVolumeControls({
    state,
    conference,
    localVolume,
    localMuted,
    toggleLocalMute,
    onLocalVolumeChange,
  });

  return {
    sensors,
    handleDragStart,
    handleDragOver,
    handleDragEnd,
    handleDragCancel,
    activeDrag,
    displayName,
    auth: {
      isAuthed,
      isChecked: isAuthChecked,
      isBusy: authBusy,
      loginName,
      password,
      confirmPassword,
      isRegisterMode,
      publicRoomLink:
        roomSlug && typeof window !== "undefined"
          ? `${window.location.origin}/${roomSlug}`
          : "",
      roomSlugInput,
      roomListedInput,
      isSlugBusy: slugBusy,
      onLoginNameChange: setLoginName,
      onPasswordChange: setPassword,
      onConfirmPasswordChange: setConfirmPassword,
      onToggleMode: () => setIsRegisterMode((prev) => !prev),
      onSubmit: isRegisterMode ? register : login,
      login: userLogin,
      account,
      canManageAccount: Boolean(canManageAccount),
      showAdminBack: Boolean(showAdminBack),
      conference,
      onRoomSlugInputChange: setRoomSlugInput,
      onRoomListedInputChange: setRoomListedInput,
      onLogout: logout,
      showNotice,
    },
    playback: {
      audioRef,
      currentLabel,
      listeners: state?.listeners ?? 0,
      isPlaying: Boolean(state?.is_playing),
      isRepeatOn: Boolean(state?.repeat_one),
      positionLabel: formatSeconds(
        isSeekingRef.current ? Number(seekValue) : state?.position ?? 0
      ),
      seekValue,
      seekMax: Math.max(
        1,
        Math.ceil(resolvedDuration)
      ),
      onSeekChange: (event) => {
        isSeekingRef.current = true;
        setSeekValue(event.target.value);
      },
      onSeekCommit: (event) => onSeek(event.target.value),
      onPause: () => sendAction("/api/studio/pause"),
      onResume: () => {
        unlockAudio();
        return sendAction("/api/studio/resume");
      },
      onSkip: () => sendAction("/api/studio/skip"),
      onToggleRepeat: () =>
        sendAction("/api/studio/repeat", {
          repeat_one: !Boolean(state?.repeat_one),
        }),
      ...volumeControls,
      outputForcedMuted,
    },
    queue: {
      entries: queueEntries,
      ids: renderQueueIds,
      onForcePlay: (index) =>
        sendAction("/api/studio/queue/force-play", { index }),
      onRemove: (index) => sendAction("/api/studio/queue/remove", { index }),
      displayName,
    },
    library: {
      sections: libraryState.sections,
      tracks: libraryState.tracks,
      uploads: libraryState.uploads,
      youtubeDownloads: libraryState.youtubeDownloads,
      onDismissYoutubeDownload: libraryState.youtube?.dismissYoutubeDownload,
      youtubeModal: {
        isOpen: Boolean(libraryState.youtube?.isYoutubeOpen),
        url: libraryState.youtube?.youtubeUrl ?? "",
        error: libraryState.youtube?.youtubeError ?? "",
        onUrlChange: libraryState.youtube?.setYoutubeUrl,
        onSubmit: libraryState.youtube?.submitYoutube,
        onClose: libraryState.youtube?.closeYoutube,
      },
      isEditing: libraryState.isEditingLibrary,
      isDragging: libraryState.isDragging,
      fileInputRef: libraryState.fileInputRef,
      onUpload: libraryState.upload,
      onTriggerUpload: libraryState.triggerUpload,
      onTriggerYoutube: libraryState.triggerYoutube,
      onToggleEdit: libraryState.toggleEdit,
      onDragOver: libraryState.onFileDragOver,
      onDragLeave: libraryState.onFileDragLeave,
      onDrop: libraryState.onFileDrop,
      isBusy: libraryBusy,
      editingTrackId: libraryState.editingTrackId,
      editingValue: libraryState.editingValue,
      onEditValueChange: libraryState.setEditingValue,
      onStartRename: libraryState.startRename,
      onCancelRename: libraryState.cancelRename,
      onConfirmRename: libraryState.guardRenamePlaying,
      onRequestDelete: libraryState.guardDeletePlaying,
      newSectionName: libraryState.newSectionName,
      onNewSectionNameChange: libraryState.setNewSectionName,
      isAddingSection: libraryState.isAddingSection,
      onStartAddSection: libraryState.startAddSection,
      onCancelAddSection: libraryState.cancelAddSection,
      onCreateSection: libraryState.createSection,
      editingSectionId: libraryState.editingSectionId,
      editingSectionName: libraryState.editingSectionName,
      onEditingSectionNameChange: libraryState.setEditingSectionName,
      onStartRenameSection: libraryState.startRenameSection,
      onCancelRenameSection: libraryState.cancelRenameSection,
      onConfirmRenameSection: libraryState.confirmRenameSection,
      onDeleteSection: libraryState.deleteSection,
      collapsedSectionIds: libraryState.collapsedSectionIds,
      onToggleSectionCollapsed: libraryState.toggleSectionCollapsed,
      onPlay: (id) => sendAction("/api/studio/play", { id }),
      onQueue: (id) => sendAction("/api/studio/queue", { id }),
      displayName,
    },
    theme: {
      current: theme,
      onChange: setTheme,
      isBusy: themeBusy,
    },
    hotkeys: {
      show: showHotkeys,
      onToggle: () => setShowHotkeys((prev) => !prev),
      isHydrated,
    },
    easter: {
      interactionToken,
      onInteract: bumpInteraction,
    },
    deleteTarget,
    onCancelDelete: clearDeleteTarget,
    onConfirmDelete: confirmDelete,
    isDeleteBusy: libraryBusy,
    notice,
  };
}
